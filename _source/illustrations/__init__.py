"""Deterministic, original SVG illustrations for publication detail pages.

The four kissing-number papers use figure plates (``kissing``) whose SVG files are
pre-generated by ``_source/tools/kissing_figures``; every other paper has one figure
generated here at build time.
"""
from . import kissing, kernels, constraints, language, learning


def build_illustrations():
    figures = {}
    for module in (kissing, kernels, constraints, language, learning):
        group = module.build_figures()
        overlap = figures.keys() & group.keys()
        if overlap:
            raise ValueError(f'Duplicate paper illustrations: {overlap}')
        figures.update(group)
    return figures
