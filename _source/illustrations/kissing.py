def plate_files(plate):
    return [plate['hero']['file']] + [f['file'] for f in plate['figs']]


def build_figures():
    out = {}
    for slug, plate in PLATES.items():
        for name in plate_files(plate):
            if not (SVG_DIR / name).is_file():
                raise FileNotFoundError(f'Missing plate figure {name}; run _source/tools/kissing_figures/generate.py')
        out[slug] = {'plate': plate, 'files': [SVG_DIR / n for n in plate_files(plate)],
                     'source_url': plate['source_url']}
    return out
